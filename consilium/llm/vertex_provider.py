"""Substrate: the Vertex AI Gemini provider, behind the same protocol.

This provider exists for one reason, and it is a measurement reason rather than a product one.
``docs/gcp-migration-eval.md`` compared the legacy router on ``claude-haiku-5-5`` against the ADK
orchestrator on ``gemini-2.5-flash`` and found a red-flag regression it could not attribute,
because that run moved the orchestrator and the agent model at the same time.  Holding the
orchestrator fixed and moving only the model is what separates them, and before this file the
legacy router had no way to reach Gemini: ``CONSILIUM_PROVIDER`` was ``openai | anthropic | mock``
and Vertex was wired only into the ADK tree.

It uses ``google.genai``, which is already a dependency of ``google-adk``, so the third arm costs
no new package.

Four things differ from the other two providers and are handled here rather than leaked upward:

* **The system prompt is ``config.system_instruction``**, not a message.  Neutral ``system``
  messages are lifted out and concatenated, as the Anthropic provider does.
* **Roles are ``user`` and ``model``**, and there is no ``tool`` role: a tool result is a
  ``function_response`` part on a *user* turn.  Consecutive neutral ``tool`` messages merge into
  one turn, again as on Anthropic.
* **Tool calls carry no id.**  Gemini returns a function name and arguments; the neutral
  :class:`~consilium.llm.base.ToolCall` needs an id, and the ReAct loop needs that id to match the
  result back to the call, so one is synthesised per call (``call_0``, ``call_1``, …) and the
  matching ``function_response`` is keyed by *name*, which is what the wire format matches on.
* **Thinking tokens are billed as output.**  ``thoughts_token_count`` is added into
  ``completion_tokens``, the same convention ``consilium/adk/agents.py`` uses, so a Gemini turn
  costs the same in this trace as it does in an ADK trace and ``eval/pricing.yaml``'s
  ``vertexai/gemini-2.5-flash`` rate applies unchanged to both.

The provider label is ``vertexai`` for exactly that reason: it is the key the cost table is
already written against, and a second label for the same billing surface would silently produce a
run whose cost is ``not measured``.
"""

from __future__ import annotations

from collections.abc import AsyncIterator, Sequence
from typing import Any

from google import genai
from google.genai import errors as genai_errors
from google.genai import types as genai_types
from tenacity import (
    AsyncRetrying,
    retry_if_exception_type,
    stop_after_attempt,
    wait_exponential,
)

from consilium.llm.base import (
    Delta,
    LLMResponse,
    Message,
    StopReason,
    ToolCall,
    ToolSchema,
    Usage,
    record_llm_call,
    tool_names,
)
from consilium.trace import Tracer, stopwatch

DEFAULT_MODEL = "gemini-2.5-flash"

#: The label every ``llm_call`` this provider writes carries, and the key ``eval/pricing.yaml``
#: prices.  Shared with the ADK path on purpose; see the module docstring.
PROVIDER_LABEL = "vertexai"

MAX_ATTEMPTS = 4

#: Gemini's ``finish_reason`` names, mapped onto the neutral set.  ``MALFORMED_FUNCTION_CALL`` is
#: an error rather than a stop: the model tried to call a tool and produced something unparseable,
#: and reporting it as a clean stop would let the ReAct loop treat a broken turn as a finished one.
_STOP_REASONS: dict[str, StopReason] = {
    "STOP": "stop",
    "MAX_TOKENS": "length",
    "SAFETY": "content_filter",
    "RECITATION": "content_filter",
    "PROHIBITED_CONTENT": "content_filter",
    "SPII": "content_filter",
    "BLOCKLIST": "content_filter",
    "MALFORMED_FUNCTION_CALL": "error",
}

#: JSON Schema keywords Gemini's ``FunctionDeclaration`` does not accept.  The registry's schemas
#: are generated by Pydantic and carry a few of these; they are dropped rather than translated,
#: because a dropped keyword costs a little validation strictness while an unrecognised one is a
#: 400 that would take the whole arm down.
_UNSUPPORTED_SCHEMA_KEYS = frozenset(
    {"additionalProperties", "$schema", "$defs", "definitions", "title", "examples", "default"}
)


def _clean_schema(node: Any) -> Any:
    """Strip keywords Gemini rejects, recursively, leaving the shape intact."""
    if isinstance(node, dict):
        return {
            key: _clean_schema(value)
            for key, value in node.items()
            if key not in _UNSUPPORTED_SCHEMA_KEYS
        }
    if isinstance(node, list):
        return [_clean_schema(item) for item in node]
    return node


def to_gemini_tools(tools: Sequence[ToolSchema]) -> list[genai_types.Tool]:
    """Unwrap OpenAI-format tool definitions into one Gemini ``Tool`` of function declarations.

    One ``Tool`` holding every declaration, not one per function: the API treats the list as
    alternative tool *sources*, and declaring seven sources of one function each is a shape the
    model is documented to handle worse than one source of seven functions.
    """
    declarations: list[genai_types.FunctionDeclaration] = []
    for tool in tools:
        function = tool.get("function", tool)
        parameters = _clean_schema(function.get("parameters", {"type": "object", "properties": {}}))
        declarations.append(
            genai_types.FunctionDeclaration(
                name=function["name"],
                description=function.get("description", ""),
                parameters=parameters,
            )
        )
    return [genai_types.Tool(function_declarations=declarations)]


def to_gemini_contents(
    messages: Sequence[Message],
) -> tuple[str | None, list[genai_types.Content]]:
    """Split neutral messages into the system instruction and the ``contents`` list."""
    system_parts: list[str] = []
    contents: list[genai_types.Content] = []

    for message in messages:
        if message.role == "system":
            if message.content:
                system_parts.append(message.content)
            continue

        if message.role == "tool":
            part = genai_types.Part.from_function_response(
                name=message.name or message.tool_call_id or "tool",
                response={"result": message.content or ""},
            )
            # A function response is a user turn.  Consecutive results belong to one turn, for the
            # reason spelled out in the Anthropic provider: separate turns describe a conversation
            # that did not happen.
            if contents and contents[-1].role == "user" and contents[-1].parts is not None:
                contents[-1].parts.append(part)
            else:
                contents.append(genai_types.Content(role="user", parts=[part]))
            continue

        if message.role == "assistant":
            parts: list[genai_types.Part] = []
            if message.content:
                parts.append(genai_types.Part.from_text(text=message.content))
            parts.extend(
                genai_types.Part.from_function_call(name=call.name, args=call.arguments)
                for call in message.tool_calls
            )
            if parts:
                contents.append(genai_types.Content(role="model", parts=parts))
            continue

        contents.append(
            genai_types.Content(
                role="user", parts=[genai_types.Part.from_text(text=message.content or "")]
            )
        )

    return ("\n\n".join(system_parts) if system_parts else None), contents


def from_gemini_response(payload: Any, *, model: str, latency_ms: float) -> LLMResponse:
    """Translate a Gemini ``GenerateContentResponse`` into the neutral response type."""
    text: list[str] = []
    calls: list[ToolCall] = []

    candidates = payload.candidates or []
    candidate = candidates[0] if candidates else None
    content = getattr(candidate, "content", None) if candidate is not None else None
    for part in getattr(content, "parts", None) or []:
        if getattr(part, "thought", False):
            # Thinking parts are billed and counted, never delivered: the neutral response carries
            # the answer, and a summarised chain of thought pasted into it would reach the user.
            continue
        if getattr(part, "function_call", None) is not None:
            call = part.function_call
            arguments = dict(call.args) if call.args else {}
            calls.append(
                ToolCall(id=f"call_{len(calls)}", name=call.name or "", arguments=arguments)
            )
        elif getattr(part, "text", None):
            text.append(part.text)

    finish = getattr(candidate, "finish_reason", None) if candidate is not None else None
    finish_name = getattr(finish, "name", None) or (str(finish) if finish else "")
    stop_reason: StopReason = _STOP_REASONS.get(finish_name, "other")
    # A turn that asked for tools is a tool-call turn whatever the finish reason says; Gemini
    # reports STOP alongside function calls, and the ReAct loop branches on this field.
    if calls:
        stop_reason = "tool_calls"

    usage = getattr(payload, "usage_metadata", None)
    prompt_tokens = (getattr(usage, "prompt_token_count", 0) or 0) if usage else 0
    completion_tokens = (
        (getattr(usage, "candidates_token_count", 0) or 0)
        + (getattr(usage, "thoughts_token_count", 0) or 0)
        if usage
        else 0
    )

    return LLMResponse(
        content="".join(text) or None,
        tool_calls=calls,
        stop_reason=stop_reason,
        provider=PROVIDER_LABEL,
        model=getattr(payload, "model_version", None) or model,
        usage=Usage(prompt_tokens=prompt_tokens, completion_tokens=completion_tokens),
        latency_ms=latency_ms,
    )


class VertexProvider:
    """Vertex AI Gemini, behind :class:`~consilium.llm.base.LLMProvider`.

    Authentication is Application Default Credentials -- the Cloud Run service account in
    deployment, ``gcloud auth application-default login`` locally -- so there is no key to hold and
    none to leak into a trace.  That is why this provider takes a project and a location where the
    other two take an API key.
    """

    def __init__(
        self,
        *,
        project: str,
        location: str,
        model: str = DEFAULT_MODEL,
        max_tokens: int | None = None,
        max_attempts: int = MAX_ATTEMPTS,
        backoff_multiplier: float = 1.0,
        client: Any | None = None,
    ) -> None:
        self.name = PROVIDER_LABEL
        self.model = model
        self.max_tokens = max_tokens
        self.max_attempts = max_attempts
        self.backoff_multiplier = backoff_multiplier
        self._client = client or genai.Client(vertexai=True, project=project, location=location)

    def _retrying(self) -> AsyncRetrying:
        return AsyncRetrying(
            retry=retry_if_exception_type(
                (genai_errors.ServerError, genai_errors.ClientError, TimeoutError)
            ),
            stop=stop_after_attempt(self.max_attempts),
            wait=wait_exponential(multiplier=self.backoff_multiplier, min=0, max=20),
            reraise=True,
        )

    def _config(
        self, system: str | None, tools: Sequence[ToolSchema] | None, kwargs: dict[str, Any]
    ) -> genai_types.GenerateContentConfig:
        config: dict[str, Any] = dict(kwargs)
        if system is not None:
            config["system_instruction"] = system
        if tools:
            config["tools"] = to_gemini_tools(tools)
            # Without this the SDK runs its own tool loop and returns a finished answer, which
            # would move the ReAct loop's budget enforcement inside the SDK where the project
            # cannot count it.  Every tool call has to come back to `consilium/agents/loop.py`.
            config["automatic_function_calling"] = genai_types.AutomaticFunctionCallingConfig(
                disable=True
            )
        if self.max_tokens is not None:
            config["max_output_tokens"] = self.max_tokens
        return genai_types.GenerateContentConfig(**config)

    async def chat(
        self,
        messages: Sequence[Message],
        *,
        tools: Sequence[ToolSchema] | None = None,
        tracer: Tracer | None = None,
        caller: str | None = None,
        **kwargs: Any,
    ) -> LLMResponse:
        system, contents = to_gemini_contents(messages)
        config = self._config(system, tools, kwargs)

        with stopwatch() as elapsed_ms:
            async for attempt in self._retrying():
                with attempt:
                    payload = await self._client.aio.models.generate_content(
                        model=self.model, contents=contents, config=config
                    )

        response = from_gemini_response(payload, model=self.model, latency_ms=elapsed_ms())
        record_llm_call(tracer, caller, response, tool_names(tools))
        return response

    async def stream_chat(
        self,
        messages: Sequence[Message],
        *,
        tracer: Tracer | None = None,
        caller: str | None = None,
        **kwargs: Any,
    ) -> AsyncIterator[Delta]:
        """Stream answer tokens.  No tools, by the protocol's scope decision in ``base.py``."""
        system, contents = to_gemini_contents(messages)
        config = self._config(system, None, kwargs)

        prompt_tokens = 0
        completion_tokens = 0
        stop_reason: StopReason = "stop"

        with stopwatch() as elapsed_ms:
            stream = await self._client.aio.models.generate_content_stream(
                model=self.model, contents=contents, config=config
            )
            async for chunk in stream:
                usage = getattr(chunk, "usage_metadata", None)
                if usage:
                    prompt_tokens = getattr(usage, "prompt_token_count", 0) or prompt_tokens
                    completion_tokens = (
                        (getattr(usage, "candidates_token_count", 0) or 0)
                        + (getattr(usage, "thoughts_token_count", 0) or 0)
                    ) or completion_tokens
                candidates = chunk.candidates or []
                candidate = candidates[0] if candidates else None
                finish = getattr(candidate, "finish_reason", None) if candidate else None
                if finish is not None:
                    finish_name = getattr(finish, "name", None) or str(finish)
                    stop_reason = _STOP_REASONS.get(finish_name, "other")
                for part in getattr(getattr(candidate, "content", None), "parts", None) or []:
                    if getattr(part, "thought", False):
                        continue
                    if getattr(part, "text", None):
                        yield Delta(content=part.text)

        usage_total = Usage(prompt_tokens=prompt_tokens, completion_tokens=completion_tokens)
        yield Delta(stop_reason=stop_reason, usage=usage_total)
        record_llm_call(
            tracer,
            caller,
            LLMResponse(
                content=None,
                stop_reason=stop_reason,
                provider=PROVIDER_LABEL,
                model=self.model,
                usage=usage_total,
                latency_ms=elapsed_ms(),
            ),
            [],
        )
