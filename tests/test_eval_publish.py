def test_the_headline_figures_are_what_summary_json_carries(summary: dict[str, Any]) -> None:
    """The README's negative headline, asserted against its evidence."""
    safety = {result["config"]: result["safety"] for result in summary["results"]}
    retrieval = {result["config"]: result["retrieval"] for result in summary["results"]}
    routing = {result["config"]: result["routing"] for result in summary["results"]}

    for config, expected in HEADLINE.items():
        for field, value in expected.items():
            assert safety[config][field] == pytest.approx(value), (config, field)

    assert safety["full"]["red_flag_false_negatives"] == 14
    assert safety["baseline_llm"]["red_flag_false_negatives"] == 3
    assert safety["full"]["n_red_flag_items"] == 28
    assert retrieval["full"]["recall_at_5_union"] == pytest.approx(0.8568232662192394)
    assert retrieval["single_agent_rag"]["recall_at_5_union"] == pytest.approx(0.7214765100671141)
    assert routing["full"]["accuracy"] == pytest.approx(0.8666666666666667)
    assert routing["full"]["fallback_rate"] == 0.0


def test_the_repair_rescued_nothing_in_either_full_configuration(summary: dict[str, Any]) -> None:
    """The mechanism sentence in the README and in `docs/SAFETY.md`, as an assertion.

    Red-flag recall minus `model_escalated_unaided` is what the input-side banner contributed.  It
    is one item of 28 in the two configurations where the model was already escalating, and exactly
    zero in both `full` configurations -- so the drop from 0.893 to 0.500 is the model's own
    escalation language disappearing, not a guard that stopped working.
    """
    safety = {result["config"]: result["safety"] for result in summary["results"]}
    contribution = {
        config: safety[config]["red_flag_recall"] - safety[config]["model_escalated_unaided"]
        for config in HEADLINE
    }

    assert contribution["baseline_llm"] == pytest.approx(1 / 28)
    assert contribution["single_agent_rag"] == pytest.approx(1 / 28)
    assert contribution["full"] == 0.0
    assert contribution["full_no_memory"] == 0.0


def test_only_the_full_configurations_ran_the_risk_skill(summary: dict[str, Any]) -> None:
    """`assess_risk` lives on the diagnostic agent, and only a router reaches that agent.

    This is the structural half of the regression's mechanism: the two configurations that lose
    red-flag recall are exactly the two that call the skill whose non-match text they then repeat.
    """
    skills = {
        result["config"]: result["usage"]["tool_calls_by_skill"] for result in summary["results"]
    }

    assert "assess_risk" not in skills["baseline_llm"]
    assert "assess_risk" not in skills["single_agent_rag"]
    assert skills["full"]["assess_risk"] == 51
    assert skills["full_no_memory"]["assess_risk"] == 50


def test_the_judge_agreement_field_is_null_and_the_readme_carries_the_kappa_anyway(
    summary: dict[str, Any],
) -> None:
    """The sweep does not ingest the validation file, so `report.md` says "not measured".

    `docs/EVALUATION.md` §4.2 holds the measured kappa, and the owner's decision of 2026-08-30 is
    that every published faithfulness number carries it.  The README is where those numbers are
    most likely to be read on their own, so the caveat has to be in its text rather than inherited
    from a file it links to.
    """
    assert all(result["judge"]["cohens_kappa"] is None for result in summary["results"])
    assert "Agreement with a human has **not been measured**" in (
        (PUBLISHED_DIR / "report.md").read_text(encoding="utf-8")
    )
    assert "kappa = 0.592" in README.read_text(encoding="utf-8")


def test_the_rates_are_recoverable_from_the_published_costs(summary: dict[str, Any]) -> None:
    """`eval/pricing.yaml` ships empty and the operator's copy is not committed.

    Each configuration publishes prompt tokens, completion tokens and cost per turn, which is one
    equation per configuration in two unknowns.  A solution that reproduces all five to floating
    point is the rate card the run was priced with, recovered from the published artifact rather
    than copied from a vendor page.
    """
    rates = recover_rates(summary)

    assert rates.input_per_token * 1e6 == pytest.approx(0.15)
    assert rates.output_per_token * 1e6 == pytest.approx(0.60)
    assert rates.max_residual < 1e-12


