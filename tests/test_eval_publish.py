def test_the_calibration_divides_reconstructed_characters_by_charged_tokens(
    sessions: dict[str, list[list[dict[str, Any]]]], golden: list[GoldenItem]
) -> None:
    calibration = calibrate(sessions, golden)

    assert calibration.turns == 150
    assert calibration.prompt_characters == CALIBRATION_CHARACTERS
    assert calibration.prompt_tokens == CALIBRATION_TOKENS
    assert calibration.characters_per_token == pytest.approx(4.438, abs=0.001)


def test_the_judge_volume_reconstruction_is_what_the_document_publishes(
    sessions: dict[str, list[list[dict[str, Any]]]], golden: list[GoldenItem]
) -> None:
    """The judge's calls were never traced, so §5.3's figures are a reconstruction.

    A reconstruction that nobody can reproduce is worse than no figure at all, so it is computed
    here from the same committed artifacts and required to match the document in both directions.
    """
    documents = {document.doc_id: document for document in load_corpus(CORPUS_DIR)}
    volume = judge_volume(
        sessions,
        items=golden,
        conversations=load_multiturn(Path("eval/data/multiturn.jsonl")),
        documents=documents,
    )
    calibration = calibrate(sessions, golden)
    document = EVALUATION_DOC.read_text(encoding="utf-8")

    assert volume.calls == JUDGE_CALLS
    assert volume.prompt_characters == JUDGE_PROMPT_CHARACTERS
    # `full_budget_6` is scored and never judged, so it contributes no judge call at all.
    assert [name for name, _, _ in volume.per_config] == [
        "baseline_llm",
        "single_agent_rag",
        "full",
        "full_no_memory",
        "full (multi-turn)",
    ]
    assert f"{JUDGE_CALLS:,}" in document
    assert f"{JUDGE_PROMPT_CHARACTERS:,}" in document
    assert f"{volume.prompt_tokens(calibration):,}" in document


def test_the_sizing_replay_is_what_the_document_publishes(
    sessions: dict[str, list[list[dict[str, Any]]]],
    golden: list[GoldenItem],
    summary: dict[str, Any],
) -> None:
    """The A3 close-out's "where the projection went wrong", recomputed.

    The first ten golden items are one category block, and the planner routed none of them in
    parallel; the extrapolation from that slice therefore priced the cheap mode only.
    """
    rates = recover_rates(summary)
    rows = sizing_replay(sessions, items=golden, rates=rates, slice_size=10)
    projected = sum(row.slice_projection for row in rows)
    measured = sum(row.full_cost for row in rows)
    document = EVALUATION_DOC.read_text(encoding="utf-8")

    assert {row.slice_turns for row in rows} == {10}
    assert {row.full_turns for row in rows} == {150}
    assert projected == pytest.approx(0.3117, abs=0.0001)
    assert measured == pytest.approx(0.4700, abs=0.0001)
    assert f"${projected:.4f}" in document
    assert f"${measured:.4f}" in document


def test_the_sizing_slice_saw_no_parallel_turn(
    sessions: dict[str, list[list[dict[str, Any]]]], golden: list[GoldenItem]
) -> None:
    """Why the slice under-priced `full`: one category block, routed single every time."""
    head = [item.id for item in golden[:10]]
    modes = [
        event["mode"]
        for item_id in head
        for event in sessions[f"full-{item_id}"][0]
        if event["type"] == "route"
    ]

    assert modes == ["single"] * 10


