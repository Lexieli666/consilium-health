def test_the_published_tree_matches_its_manifest() -> None:
    """Every published file hashes to what `MANIFEST.json` says it does."""
    assert verify_manifest(PUBLISHED_DIR) == []


def test_the_manifest_covers_one_trace_per_session_plus_the_two_verbatim_files(
    summary: dict[str, Any],
) -> None:
    manifest = json.loads((PUBLISHED_DIR / "MANIFEST.json").read_text(encoding="utf-8"))
    names = set(manifest["files"])

    assert {"summary.json", "report.md"} <= names
    assert manifest["n_traces"] == len(names) - 2
    # 150 items x 4 ablation configurations, 50 more for the budget diagnostic, 29 multi-turn
    # conversations.  The count is arithmetic on the run, not a magic number.
    assert manifest["n_traces"] == summary["n_items"] * 4 + 50 + 29


def test_a_session_becomes_one_file_with_its_turns_in_numeric_order(tmp_path: Path) -> None:
    """`10.jsonl` must not sort before `2.jsonl`, which is what string ordering would do."""
    session = tmp_path / "full-mt-m-001"
    session.mkdir()
    for index in (0, 2, 10):
        (session / f"{index}.jsonl").write_text(
            json.dumps({"type": "turn", "turn_index": index}) + "\n", encoding="utf-8"
        )

    payload = read_session(session)

    assert payload["session_id"] == "full-mt-m-001"
    assert [turn["turn_index"] for turn in payload["turns"]] == [0, 2, 10]


def test_publishing_copies_the_two_reports_byte_for_byte(tmp_path: Path) -> None:
    """`summary.json` and `report.md` are copied, never re-rendered from the summary."""
    run = tmp_path / "20260830T170133Z"
    (run / "runs" / "full-g-gh-001").mkdir(parents=True)
    (run / "runs" / "full-g-gh-001" / "0.jsonl").write_text(
        json.dumps({"type": "turn", "question": "q", "answer": "a"}) + "\n", encoding="utf-8"
    )
    (run / "summary.json").write_bytes(b'{"commit": "abc123"}\n')
    (run / "report.md").write_bytes(b"# Evaluation results\r\n\r\nnot regenerated\n")
    out = tmp_path / "published"
    out.mkdir()

    manifest = publish_run(run, out)

    assert (out / "summary.json").read_bytes() == b'{"commit": "abc123"}\n'
    assert (out / "report.md").read_bytes() == b"# Evaluation results\r\n\r\nnot regenerated\n"
    assert manifest["n_traces"] == 1
    assert verify_manifest(out) == []


def test_the_manifest_notices_an_edited_trace(tmp_path: Path) -> None:
    run = tmp_path / "run"
    (run / "runs" / "full-g-gh-001").mkdir(parents=True)
    (run / "runs" / "full-g-gh-001" / "0.jsonl").write_text("{}\n", encoding="utf-8")
    (run / "summary.json").write_text("{}\n", encoding="utf-8")
    (run / "report.md").write_text("#\n", encoding="utf-8")
    out = tmp_path / "published"
    out.mkdir()
    publish_run(run, out)

    (out / "traces" / "full-g-gh-001.json").write_text('{"session_id": "x"}\n', encoding="utf-8")

    assert verify_manifest(out) == ["changed: traces/full-g-gh-001.json"]


