"""The published run: the layout, the manifest, and the two reconstructions built on it.

Three things are asserted here, and they exist for three different failure modes.

**The published tree still is what was published.**  `eval/results/published/` is the only path
under `eval/results/` that git tracks, and every number in the README and in `docs/` is read out of
it.  `MANIFEST.json` is recomputed against the files beside it, so a trace edited by hand -- or a
`summary.json` regenerated by a later version of `eval/report.py` -- fails here rather than
silently changing what a published number refers to.

**The headline figures are pinned.**  The README states them in prose and the ablation table
repeats them; both are read from `summary.json` and neither is recomputed at build time.  Pinning
them means the document and the evidence cannot drift apart without a test saying so, which is the
same rule `tests/test_eval_drafts.py` applies to the golden set's frozen digests.

**The two reconstructions are reproducible.**  `docs/EVALUATION.md` §5.3 publishes numbers that
`eval/run.py` did not produce -- the judge's untraced prompt volume, and a replay of the A3 sizing
slice.  They are computed from committed artifacts by `eval/publish.py`, so they are checkable; the
tests below recompute them and require the results to appear in the document, in both directions.
"""

